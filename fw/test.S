# Первая программа: проверка RAM и записи по адресу светодиодов.

    .text
    .globl _start
_start:
    # Часть 1: записать слово в RAM и прочитать его обратно.
    li   t2, 0x55           # значение
    li   t3, 0x100          # адрес в RAM, вне кода программы
    sw   t2, 0(t3)
    lw   t4, 0(t3)          # после чтения t4 должен стать 0x55

    # Часть 2: бесконечно писать счётчик по адресу светодиодов.
    li   t0, 0x10000000     # адрес регистра светодиодов
    li   t1, 0              # счётчик
loop:
    sw   t1, 0(t0)
    addi t1, t1, 1
    j    loop               # программа не должна заканчиваться
